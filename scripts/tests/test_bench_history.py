    def test_the_script_writes_every_filesystem_a_run_measured(self):
        """TASK-79.64: run as the script is, its paths a measurements directory of its own,
        bench-history.py writes each filesystem a run measured, a fork's and a followed writer's
        among them, which its list of filesystems left out."""
        root = Path(tempfile.mkdtemp())
        measurements = root / "docs" / "measurements"
        measurements.mkdir(parents=True)
        run(
            measurements,
            "2026-10-17T1609Z",
            {
                "ext4-virtio-blk": 1000.0,
                "fxfs-guest-dax-fork-warm": 300.0,
                "fxfs-guest-dax-followed": 1200.0,
            },
        )
        module = script.load("bench-history")
        module.ROOT, module.MEASUREMENTS = root, measurements
        module.OUTPUT = measurements / "fs-bench-history.md"
        module.main()
        written = module.OUTPUT.read_text()
        self.assertEqual(
            [backend in written for backend in ["fxfs-guest-dax-fork-warm", "fxfs-guest-dax-followed"]],
            [True, True],
        )

    def test_empty_directories_are_no_runs(self):
        """A run's directory left empty, as a run that copied nothing back leaves it, is no row."""
        measurements = Path(tempfile.mkdtemp())
        run(measurements, "2026-10-17T1609Z", {"fxfs-guest-dax": 1500.0})
        (measurements / "gce-fs-bench-2026-10-17T1415Z").mkdir()
        page = bench_history.history(measurements)
        self.assertEqual(
            ["2026-10-17T1609Z" in page, "2026-10-17T1415Z" in page], [True, False]
        )

    def test_runs_are_in_the_order_they_started(self):
        measurements = Path(tempfile.mkdtemp())
        # When bench-gce.sh's run began, as the run's directory on the host is named, in the
        # log of bench.sh there; or else the time the run is named for.
        run(measurements, "zstd-0", {"fxfs-guest-dax": 1500.0},
            files={"bench.log": "Results: /home/u/run-20261019T045755Z/results\n"})
        run(measurements, "2026-10-19T0500Z", {"fxfs-guest-dax": 1550.0})
        run(measurements, "followed-2026-10-19T0828Z", {"fxfs-guest-dax": 1600.0},
            files={"bench.log": "Logs: /home/u/run-20261019T083012Z/results/logs\n"})
        run(measurements, "2026-10-10T1652Z", {"fxfs-guest-dax": 1400.0})
        # Named for the time and the run's mark (scripts/lib/gce.sh).
        run(measurements, "2026-10-19T0600Z-4434880c", {"fxfs-guest-dax": 1575.0})
        # Neither: last, by name.
        run(measurements, "pgbench-local", {"fxfs-guest-dax": 1450.0})
        page = bench_history.history(measurements)
        self.assertEqual(
            re.findall(r"^\| \[([^]]+)\]", page, re.M),
            ["2026-10-10T1652Z", "zstd-0", "2026-10-19T0500Z", "2026-10-19T0600Z-4434880c",
             "followed-2026-10-19T0828Z", "pgbench-local"],
        )
        self.assertIn(
            "| Workload | Unit | 2026-10-10T1652Z | zstd-0 | 2026-10-19T0500Z "
            "| 2026-10-19T0600Z-4434880c | followed-2026-10-19T0828Z | pgbench-local |\n",
            page,
        )


