"""Tests of scripts/bench-history.py, the benchmark's results over time."""

import json
import tempfile
import unittest
from pathlib import Path

import script

bench_history = script.load("bench-history")


def run(measurements, name, tps, iterations=None, files=None):
    """A run, gce-fs-bench-NAME under `measurements`: pgbench's transactions a second on each
    filesystem of `tps`, each in its `iterations` (default 1), and its other files, `files`, by
    name."""
    directory = measurements / f"gce-fs-bench-{name}"
    directory.mkdir()
    for backend, value in tps.items():
        case = {
            "case": f"bench-fs-{backend}",
            "backend": backend,
            "host_os": "linux",
            "vmm": "firecracker",
            "iterations": (iterations or {}).get(backend, 1),
            "results": [
                {"workload": "pgbench-tps", "unit": "tps", "higher_is_better": True,
                 "values": [value]}
            ],
        }
        (directory / f"bench-fs-{backend}.json").write_text(json.dumps(case))
    for file, text in (files or {}).items():
        (directory / file).write_text(text)


