"""Tracks the filesystem benchmark's results over time, as a Markdown page.

Reads every run under docs/measurements (gce-fs-bench-<time>/, as scripts/bench-gce.sh keeps
them): the measurements each case wrote, the source measured (source.txt), how long the run took
(host.txt) and what it was for (note.md). Writes docs/measurements/fs-bench-history.md: the runs,
in the order they started (`started`), then for each filesystem each workload's median in every
run, and for each filesystem how many times slower than what it compares with
(scripts/bench_results.py) it was, in the runs that measured both.

Usage: scripts/bench-history.py
"""

import importlib.util
import re
import statistics
from datetime import datetime
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
MEASUREMENTS = ROOT / "docs" / "measurements"
OUTPUT = MEASUREMENTS / "fs-bench-history.md"

# By its path, which needs no module path naming this directory.
spec = importlib.util.spec_from_file_location("bench", ROOT / "scripts" / "bench_results.py")
bench = importlib.util.module_from_spec(spec)
spec.loader.exec_module(bench)


def started(directory):
    """When the run in `directory` started, if it says: when bench-gce.sh named the run's directory
    on the host (run-<time>, which the log of bench.sh there names), or else the time the run is
    named for, to the minute, before the run's mark if it has one (scripts/lib/gce.sh)."""
    log = directory / "bench.log"
    if log.exists():
        stamp = re.search(r"/run-(\d{8}T\d{6}Z)/", log.read_text(errors="replace"))
        if stamp:
            return datetime.strptime(stamp.group(1), "%Y%m%dT%H%M%SZ")
    stamp = re.search(r"(\d{4}-\d{2}-\d{2}T\d{4}Z)(-[0-9a-f]{8})?$", directory.name)
    return datetime.strptime(stamp.group(1), "%Y-%m-%dT%H%MZ") if stamp else None


def load_run(directory):
    source = (directory / "source.txt").read_text() if (directory / "source.txt").exists() else ""
    revision = re.search(r"^revision (\w+)", source, re.M)
    dirty = any(line.startswith("changed ") for line in source.splitlines())
    host = (directory / "host.txt").read_text() if (directory / "host.txt").exists() else ""
    took = re.search(r"^Took (\d+)s\.", host, re.M)
    note = (directory / "note.md").read_text().strip() if (directory / "note.md").exists() else ""
    return {
        "name": directory.name.removeprefix("gce-fs-bench-"),
        "directory": directory.name,
        "started": started(directory),
        "cases": bench.load(directory),
        "revision": (revision.group(1)[:9] + (" + changes" if dirty else "")) if revision else "",
        "took": f"{took.group(1)} s" if took else "",
        "note": " ".join(note.split()),
    }


def medians(run, backend):
    report = run["cases"].get(backend)
    if not report:
        return {}
    return {
        result["workload"]: (statistics.median(result["values"]), result)
        for result in report["results"]
        if result["values"]
    }


def main():
    OUTPUT.write_text(history(MEASUREMENTS))
    print(f"Wrote {OUTPUT.relative_to(ROOT)}")


def history(measurements):
    """The page, of the runs under the directory `measurements`."""
    runs = sorted(
        (load_run(path) for path in measurements.glob("gce-fs-bench-*") if path.is_dir()),
        # Those that do not say when they started last, by name.
        key=lambda run: (run["started"] is None, run["started"] or datetime.min, run["name"]),
    )
    lines = [
        "# Filesystem benchmark history",
        "",
        "Generated by `scripts/bench-history.py` from the runs under `docs/measurements`, which",
        "`scripts/bench-gce.sh` keeps. Each run's directory has its measurements, logs, host and",
        "source; its note says what it was for. Medians of the iterations.",
        "",
        "## Runs",
        "",
        "| Run | Revision | Filesystems | Iterations | Took | Note |",
        "|---|---|---|---|---|---|",
    ]
    for run in runs:
        backends = bench.ordered(run["cases"])
        iterations = sorted({run["cases"][b]["iterations"] for b in backends})
        lines.append(
            f"| [{run['name']}]({run['directory']}/) | {run['revision']} | {', '.join(backends) or '–'} "
            f"| {', '.join(map(str, iterations)) or '–'} | {run['took'] or '–'} | {run['note'] or '–'} |"
        )
    measured = [run for run in runs if run["cases"]]
    backends = bench.ordered({backend for run in measured for backend in run["cases"]})
    for backend in backends:
        with_backend = [run for run in measured if backend in run["cases"]]
        lines += ["", f"## {backend}", ""]
        lines += table(with_backend, lambda run: medians(run, backend), lambda m: bench.fmt(m[0]))
    for backend, base in [(b, base) for b in backends for base in bench.baselines(b)]:
        both = [run for run in measured if backend in run["cases"] and base in run["cases"]]
        if not both:
            continue
        lines += ["", f"## {backend}: times slower than {base}", ""]

        def ratios(run, backend=backend, base=base):
            ours, theirs = medians(run, backend), medians(run, base)
            out = {}
            for workload, (value, result) in ours.items():
                if workload in theirs:
                    ratio = bench.ratio(value, theirs[workload][0], result["higher_is_better"])
                    out[workload] = (ratio, result)
            return out

        lines += table(both, ratios, lambda entry: bench.times(entry[0]))
    return "\n".join(lines) + "\n"


def table(runs, values_of, cell):
    """A table of each workload's cell in each run, workloads in the order the runs first have
    them."""
    values = [values_of(run) for run in runs]
    workloads, units = [], {}
    for per_run in values:
        for workload, (_, result) in per_run.items():
            if workload not in units:
                workloads.append(workload)
                units[workload] = result["unit"]
    lines = [
        "| Workload | Unit | " + " | ".join(run["name"] for run in runs) + " |",
        "|---|---|" + "---|" * len(runs),
    ]
    for workload in workloads:
        cells = [cell(per_run[workload]) if workload in per_run else "–" for per_run in values]
        lines.append(f"| {workload} | {units[workload]} | " + " | ".join(cells) + " |")
    return lines


if __name__ == "__main__":
    main()
